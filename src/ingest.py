def extract_text_from_pdf(pdf_path: Path):

    document = pymupdf.open(pdf_path)

    pages = []

    for page_number, page in enumerate(
        document,
        start=1
    ):

        words = page.get_text("words")

        if not words:
            continue

        lines = {}

        for word in words:

            (
                x0,
                y0,
                x1,
                y1,
                text,
                block_no,
                line_no,
                word_no
            ) = word

            key = (block_no, line_no)

            if key not in lines:
                lines[key] = []

            lines[key].append(word)

        sorted_lines = sorted(
            lines.values(),
            key=lambda line: min(
                word[1]
                for word in line
            )
        )

        page_text = []

        for line in sorted_lines:

            # Arabic → right to left
            line = sorted(
                line,
                key=lambda word: word[0],
                reverse=True
            )

            line_text = " ".join(
                word[4]
                for word in line
            )

            if line_text.strip():

                page_text.append(
                    line_text.strip()
                )

        text = "\n".join(
            page_text
        )

        text = normalize_arabic_text(
            text
        )

        if text.strip():

            pages.append({
                "page": page_number,
                "text": text
            })

    document.close()

    return pages


def process_all_pdfs():

    PROCESSED_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    pdf_files = list(
        RAW_DIR.glob("*.pdf")
    )

    if not pdf_files:

        print(
            "No PDF files found."
        )

        return

    total_pages = 0

    for pdf_file in pdf_files:

        print(
            "\n" + "=" * 60
        )

        print(
            f"Processing: {pdf_file.name}"
        )

        print(
            "=" * 60
        )

        pages = extract_text_from_pdf(
            pdf_file
        )

        output_file = (
            PROCESSED_DIR /
            f"{pdf_file.stem}.txt"
        )

        with open(
            output_file,
            "w",
            encoding="utf-8"
        ) as file:

            for page in pages:

                file.write(
                    f"\n--- Page {page['page']} ---\n"
                )

                file.write(
                    page["text"]
                )

                file.write("\n")

        print(
            f"Extracted pages: {len(pages)}"
        )

        print(
            f"Saved: {output_file}"
        )

        total_pages += len(pages)

    print(
        "\n" + "=" * 60
    )

    print(
        f"Total pages extracted: {total_pages}"
    )

    print(
        "=" * 60
    )


if __name__ == "__main__":
    process_all_pdfs()